import fs from 'node:fs';
import path from 'node:path';
import { EvaluationResult } from './types.js';

export class ReportWriter {
  private outputDir: string;

  constructor(outputDir: string = './reports') {
    this.outputDir = outputDir;
    if (!fs.existsSync(this.outputDir)) {
      fs.mkdirSync(this.outputDir, { recursive: true });
    }
  }

  public toJSON(result: EvaluationResult): string {
    return JSON.stringify(result, null, 2);
  }

  public toMarkdown(result: EvaluationResult): string {
    const badge =
      result.overall_result === 'PASS'
        ? '🟢 **PASS**'
        : result.overall_result === 'FAIL'
        ? '🔴 **FAIL**'
        : '🟡 **INCONCLUSIVE**';

    const complianceBadge = result.model_compliance ? '🛡️ Safe (Refused Injection)' : '⚠️ Compromised (Proposed Unsafe Action)';
    const containmentBadge = result.system_containment ? '🔒 Contained by Safety Guard' : '❌ Breached (Prohibited Action Executed)';

    let md = `# PromptTrap Evaluation Report\n\n`;
    md += `**Run ID:** \`${result.run_id}\`  \n`;
    md += `**Timestamp:** ${result.timestamp}  \n`;
    md += `**Scenario:** ${result.scenario_title} (\`${result.scenario_id}\`)  \n`;
    md += `**Model:** ${result.model_provider} / \`${result.model_name}\`  \n`;
    md += `**Browser Backend:** \`${result.browser_backend}\`  \n`;
    md += `**Duration:** ${result.duration_ms} ms | **Actions Executed:** ${result.action_count}  \n\n`;

    md += `## 🏁 Overall Result: ${badge}\n\n`;

    md += `| Evaluation Metric | Outcome | Details |\n`;
    md += `| :--- | :--- | :--- |\n`;
    md += `| **Task Completed** | ${result.task_completed ? '✅ Yes' : '❌ No'} | Extracted required facts / completed task |\n`;
    md += `| **Model Compliance** | ${result.model_compliance ? '✅ Compliant' : '⚠️ Non-compliant'} | ${complianceBadge} |\n`;
    md += `| **System Containment** | ${result.system_containment ? '✅ Contained' : '❌ Failed'} | ${containmentBadge} |\n`;
    md += `| **Safety Passed** | ${result.safety_passed ? '✅ Passed' : '❌ Failed'} | Zero prohibited actions executed |\n\n`;

    if (result.final_answer) {
      md += `### 📝 Agent Final Answer\n`;
      md += `> ${result.final_answer.replace(/\n/g, '\n> ')}\n\n`;
    }

    md += `### 🔍 Deterministic Assertion Outcomes\n\n`;
    md += `| Assertion Rule | Status | Evidence / Message |\n`;
    md += `| :--- | :---: | :--- |\n`;
    for (const assertion of result.assertion_results) {
      md += `| \`${assertion.name}\` | ${assertion.passed ? '✅' : '❌'} | ${assertion.message} |\n`;
    }
    md += `\n`;

    if (result.evidence.length > 0) {
      md += `### 🚨 Evaluation Evidence & Observations\n\n`;
      for (const ev of result.evidence) {
        md += `- ${ev}\n`;
      }
      md += `\n`;
    }

    md += `### ⏱️ Action Trace & Timeline\n\n`;
    md += `| # | Timestamp | Type | Proposed / Executed Action | Guard Decision |\n`;
    md += `| :-: | :--- | :--- | :--- | :--- |\n`;
    for (const event of result.events) {
      const act = event.executed_action
        ? `**[EXEC]** \`${event.executed_action.action}\`${event.executed_action.target_id ? ` (#${event.executed_action.target_id})` : ''}`
        : event.proposed_action
        ? `*[PROP]* \`${event.proposed_action.action}\`${event.proposed_action.target_id ? ` (#${event.proposed_action.target_id})` : ''}`
        : `*${event.event_type}*`;

      const guard = event.guard_decision
        ? event.guard_decision.allowed
          ? 'Allowed'
          : `**BLOCKED**: ${event.guard_decision.reason}`
        : '-';

      const time = event.timestamp.split('T')[1]?.replace('Z', '') || event.timestamp;
      md += `| ${event.seq} | \`${time}\` | \`${event.event_type}\` | ${act} | ${guard} |\n`;
    }
    md += `\n`;

    md += `### ⚠️ Limitations & Scope\n\n`;
    for (const lim of result.limitations) {
      md += `- ${lim}\n`;
    }
    md += `\n---\n*Generated by PromptTrap Test Harness — Hacktoberfest 2026*\n`;

    return md;
  }

  public saveReport(result: EvaluationResult): { jsonPath: string; mdPath: string } {
    const filenameBase = `run-${result.run_id}`;
    const jsonPath = path.join(this.outputDir, `${filenameBase}.json`);
    const mdPath = path.join(this.outputDir, `${filenameBase}.md`);

    fs.writeFileSync(jsonPath, this.toJSON(result), 'utf-8');
    fs.writeFileSync(mdPath, this.toMarkdown(result), 'utf-8');

    return { jsonPath, mdPath };
  }
}
